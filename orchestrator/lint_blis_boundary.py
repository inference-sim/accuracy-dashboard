#!/usr/bin/env python3
"""The dashboard reaches BLIS only through the inference-sim commands (design §5, the
accuracy-dashboard card; X7). This lint checks four things over every file git tracks:

  1. No go.mod or go.work names a BLIS module (github.com/inference-sim/blis-*).
  2. No file holds a Go import of a BLIS module, except the sites in GO_IMPORTS.
  3. No Python code outside a test (test_*.py) builds a path inside a BLIS data checkout (the
     catalog, the registry or the ledger), except the functions in DATA_READS.

  4. No shell script (*.sh) and no workflow (.github/workflows/*.yml) clones blis-substrate,
     blis-catalog, blis-registry or blis-vllm, runs `go doc` or `go list -m` on a BLIS module,
     or reads installation.md; and no Python outside a test names the substrate or blis-vllm
     commit a stack.json pins (they exist only to be cloned). Comment lines do not count.
     Sites are listed in TEXT_READS as (file, rule).

Rule 3 looks for a path built from a string constant whose first segment is one of the
directory or file names of that layout (LAYOUT): `root / "models"`, `Path(r, "coefficients")`,
`d / "units"`. It cannot see a path built only from variables; review covers those.

Every listed site is TEMPORARY, and names the command whose absence keeps it. A listed site that
no longer matches is an error too, so removing a site means removing its entry, and the lists only
shrink.

    python3 orchestrator/lint_blis_boundary.py [ROOT]
"""
from __future__ import annotations

import ast
import re
import subprocess
import sys
from pathlib import Path

BLIS_MODULE = re.compile(r"github\.com/inference-sim/blis-[A-Za-z0-9._-]+")
GO_IMPORT = re.compile(r'^\s*(?:import\s+)?(?:[A-Za-z_.][A-Za-z0-9_]*\s+)?"github\.com/inference-sim/blis-[^"]*"\s*\)?\s*$')

# The names a path inside a catalog, registry or ledger checkout starts with. `workloads` (the
# catalog's workload presets) is left out: the scorer's own work directory has a workloads/
# subdirectory (score.py), and the dashboard has never read the catalog's.
LAYOUT = {
    "catalog", "registry", "ledger", "go.mod", "go.work", "installation.md",
    "models", "hardware", "networks", "devices", "model.yaml", "graph.yaml",
    "coefficients",
    "units", "reports", "published", "ledger.yaml", "sources.yaml", "legacy-map.yaml",
}

# Files that hold a Go import of a BLIS module, and the command whose absence keeps each.
GO_IMPORTS = {
    "orchestrator/ingest/testdata/ledger/build_fixture.py":
        "TEMPORARY until an inference-sim command prints the unit list and ingest report the "
        "ledger's ingest gives a set of records: the fixture is generated by running "
        "blis-substrate's ingest package by hand",
}

# (file, function) pairs that build a path inside a BLIS data checkout, and the command whose
# absence keeps each.
DATA_READS = {
    ("orchestrator/ingest/ledger.py", "load"):
        "TEMPORARY until an inference-sim command prints the full unit list with identities "
        "(catalog/ledger/units) and the ingest report (catalog/ledger/reports); `blis ledger --list` "
        "prints only the published unit ids",
    ("orchestrator/ingest/ledger_fake.py", "write"):
        "TEMPORARY with ledger.load: writes, for tests, the ledger layout ledger.load reads",
    ("orchestrator/ingest/support.py", "Catalog.check_unambiguous"):
        "TEMPORARY until a command lists the catalog's models with their source repositories",
    ("orchestrator/ingest/cli.py", "cmd_score"):
        "TEMPORARY until a command prints the blis-latency-kernel version a build pins (go.mod)",
    ("orchestrator/ingest/support.py", "Catalog.packaging"):
        "TEMPORARY until the pinned blis reports `packaging` from `blis catalog resolve --chip` "
        "(inference-sim m1/packaging, 146e13d9): until then hardware/<chip>.yaml GPUsPerNode and "
        "GPUsPerRack are read from the catalog checkout",
    ("orchestrator/ingest/support.py", "Catalog.speculator"):
        "TEMPORARY until a command prints a catalog model graph's speculator method",
    ("orchestrator/ingest/support.py", "registry_parts"):
        "TEMPORARY until a command prints the parts the registry scopes coefficients to",
    ("orchestrator/ingest/testdata/ledger/build_fixture.py", "main"):
        "TEMPORARY with GO_IMPORTS' entry for this file: runs blis-substrate's ingest in a checkout",
}

# Rule 4. (file, rule) pairs, and the command whose absence keeps each. Rules: clone, go_doc,
# go_list, installation (shell and workflows), pins (Python).
TEXT_READS = {
    (".github/workflows/api-nightly.yml", "clone"):
        "TEMPORARY until an inference-sim command prints the full unit list with identities and the "
        "ingest report (`blis ledger --list` prints only the published unit ids): the job checks out "
        "blis-substrate at the commit stack.json pins, for catalog/, registry/ and catalog/ledger",
    ("orchestrator/resolve_stack.py", "pins"):
        "TEMPORARY with the api-nightly.yml substrate checkout: prints the commit it clones",
    ("orchestrator/ingest/stack.py", "pins"):
        "TEMPORARY with the api-nightly.yml substrate checkout: stack.pins names the commits to clone",
}

_RULES = {
    "clone": re.compile(r"\bgit\b.*\bclone\b.*inference-sim/blis-(?:substrate|catalog|registry|vllm)\b"),
    "go_doc": re.compile(r"\bgo\s+doc\b"),
    "go_list": re.compile(r"\bgo\s+list\b.*-m\b.*\bblis-|\bgo\s+list\b.*\bblis-.*-m\b"),
    "installation": re.compile(r"installation\.md"),
}
_PINS = re.compile(r"\b(?:substrate|vllm_module)_commit\b")


def text_reads(rel: str, text: str) -> list[tuple[str, int]]:
    """(rule, line) for each rule-4 match: a shell script or workflow line (comments skipped)
    that fetches or inspects a BLIS module, or a Python line naming a pinned module commit."""
    hits = []
    shell = rel.endswith(".sh") or (rel.startswith(".github/workflows/") and rel.endswith(".yml"))
    for n, line in enumerate(text.splitlines(), 1):
        code = line.lstrip()
        if code.startswith("#"):
            continue
        if shell:
            hits += [(rule, n) for rule, rx in _RULES.items() if rx.search(line)]
        elif rel.endswith(".py") and _PINS.search(line):
            hits.append(("pins", n))
    return hits


def tracked(root: Path) -> list[str]:
    out = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True, check=True)
    return sorted(p for p in out.stdout.decode().split("\0") if p)


def _text(path: Path) -> str | None:
    try:
        return path.read_text()
    except (UnicodeDecodeError, OSError):
        return None


def _segment(node: ast.AST) -> str | None:
    """The first path segment of a string constant, or None for anything else."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value:
        return node.value.split("/")[0]
    return None


def data_reads(source: str) -> list[tuple[str, int, str]]:
    """(function qualname, line, segment) for each path the code builds from a LAYOUT name."""
    tree = ast.parse(source)
    hits = []

    def visit(node: ast.AST, scope: list[str]):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            scope = [*scope, node.name]
        segs = []
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
            segs = [_segment(node.right)]
        elif isinstance(node, ast.Call):
            f = node.func
            name = f.id if isinstance(f, ast.Name) else f.attr if isinstance(f, ast.Attribute) else ""
            if name in ("Path", "PurePath", "joinpath", "join", "glob", "rglob"):
                segs = [_segment(a) for a in node.args]
        for s in segs:
            if s in LAYOUT:
                hits.append((".".join(scope) or "<module>", node.lineno, s))
        for child in ast.iter_child_nodes(node):
            visit(child, scope)

    visit(tree, [])
    return hits


def check(root: Path) -> list[str]:
    problems = []
    go_seen, reads_seen, text_seen = set(), set(), set()
    for rel in tracked(root):
        path = root / rel
        name = Path(rel).name
        text = _text(path)
        if text is None:
            continue
        if name in ("go.mod", "go.work"):
            for n, line in enumerate(text.splitlines(), 1):
                m = BLIS_MODULE.search(line)
                if m:
                    problems.append(f"{rel}:{n}: names the BLIS module {m.group(0)}; the dashboard imports "
                                    f"no BLIS module (X7)")
        for n, line in enumerate(text.splitlines(), 1):
            if GO_IMPORT.match(line):
                if rel in GO_IMPORTS:
                    go_seen.add(rel)
                else:
                    problems.append(f"{rel}:{n}: a Go import of a BLIS module; the dashboard imports no BLIS "
                                    f"module (X7)")
        if not name.startswith("test_"):
            for rule, n in text_reads(rel, text):
                if (rel, rule) in TEXT_READS:
                    text_seen.add((rel, rule))
                else:
                    problems.append(f"{rel}:{n}: rule {rule}: this reads BLIS other than through a blis command "
                                    f"(X7); use the command, or list the site in TEXT_READS naming the command "
                                    f"it waits for")
        if rel.endswith(".py") and not name.startswith("test_"):
            for fn, n, seg in data_reads(text):
                if (rel, fn) in DATA_READS:
                    reads_seen.add((rel, fn))
                else:
                    problems.append(f"{rel}:{n}: {fn} builds a path into a BLIS data checkout ({seg!r}); read "
                                    f"BLIS data through a blis command (X7), or list the site in DATA_READS "
                                    f"naming the command it waits for")
    for rel in sorted(set(GO_IMPORTS) - go_seen):
        problems.append(f"GO_IMPORTS lists {rel}, which holds no Go import of a BLIS module: remove the entry")
    for rel, fn in sorted(set(DATA_READS) - reads_seen):
        problems.append(f"DATA_READS lists {rel} {fn}, which builds no path into a BLIS data checkout: "
                        f"remove the entry")
    for rel, rule in sorted(set(TEXT_READS) - text_seen):
        problems.append(f"TEXT_READS lists {rel} {rule}, which no longer matches: remove the entry")
    return problems


def main(argv: list[str]) -> int:
    root = Path(argv[0]) if argv else Path(__file__).resolve().parent.parent
    problems = check(root)
    for p in problems:
        print(p, file=sys.stderr)
    if problems:
        return 1
    print(f"lint_blis_boundary: no BLIS module import; {len(GO_IMPORTS) + len(DATA_READS) + len(TEXT_READS)} TEMPORARY sites, "
          f"each listed")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
