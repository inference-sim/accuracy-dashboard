"""GPUs per node of the machines InferenceX ran on, read from InferenceX's own runners.yaml.

A run's launch configuration usually records `resources.gpus_per_node`. When it does not, the
runner table in `inferencex_runners.json` answers for the row's hardware label. The table is
generated by `orchestrator/gen_inferencex_runners.py` from runners.yaml at the InferenceX
commits that record node sizes; nothing in it is typed by hand. Each record is a fact about
InferenceX's cluster at one commit, not about BLIS data.

InferenceX records node sizes only from 2026-07-02 (`first_recorded`). A row dated on or after
a label's first record takes the record in force at the row's date, and that is not a
substitution. A row dated before it takes the first record as a G2 substitution of kind
`later_record`, but only for a label whose size and clusters are the same in every version
that records it (`stable`).

A runner that no record lists (a runner in no cluster, or a label the newest file omits) may take
the fact from the records of its label when every record that lists the label states the same
size (design 11.3, the label-record rule). The row's runner is not known, so this applies when no
single-size record is in force for the row. The point is G2, kind `later_record`, naming the
field, the label and the records relied on (file and commit) in `record` and the latest record's
date in `date`. A label whose records state two sizes, or none, has no size (G5
value_not_recorded).
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from datetime import date
from pathlib import Path

DATA = Path(__file__).resolve().parent / "inferencex_runners.json"

SUBJECT = "cluster.gpus_per_node"
_HASH = re.compile(r"^[0-9a-f]{40}$")
_SOURCE = re.compile(r"^[A-Za-z0-9_./-]+:[1-9][0-9]*$")


class TableError(ValueError):
    """The runner table is malformed, or a lookup was asked something it cannot answer."""


@dataclass(frozen=True)
class Cluster:
    id: str
    gpus_per_node: int | None
    source: str | None            # file:line of the `gpus-per-node` line


@dataclass(frozen=True)
class Record:
    """What one label maps to in one version."""
    gpus_per_node: int | None     # None when the label has no single size here
    problem: str | None           # why gpus_per_node is None
    clusters: tuple[Cluster, ...]


@dataclass(frozen=True)
class Version:
    commit: str
    date: str                     # YYYY-MM-DD, the commit's date
    path: str
    records_node_sizes: bool


@dataclass(frozen=True)
class Label:
    stable: bool
    problems: tuple[str, ...]     # why the label is not stable
    first_recorded: Version | None
    records: dict                 # commit -> Record, for the versions that record node sizes
    label_size: int | None = None  # the one size every record that lists the label states, else None
    relied_on: tuple = ()          # those records' Versions, oldest first


@dataclass(frozen=True)
class Table:
    versions: tuple[Version, ...]
    labels: dict                  # hardware label -> Label


def stability(versions: list[Version], records: dict) -> tuple[bool, list[str], Version | None]:
    """(stable, problems, first_recorded) for one label.

    The label is stable when every version that records node sizes gives it a single size, and
    the size is the same in all of them. The clusters it maps to may differ between versions: the
    node size is a fact of the label's machines, and a record that names other clusters of the
    same size contradicts nothing. first_recorded is the
    first such version that gives it a single size."""
    problems = []
    first = None
    seen = None
    for v in versions:
        if not v.records_node_sizes:
            continue
        r = records[v.commit]
        if r.gpus_per_node is None:
            problems.append(f"{v.commit[:8]}: {r.problem}")
            continue
        if first is None:
            first = v
        key = (r.gpus_per_node, tuple(c.id for c in r.clusters))
        size = r.gpus_per_node
        if seen is None:
            seen = (v, key)
        elif size != seen[1][0]:
            problems.append(f"{v.commit[:8]}: {_describe(key)} where {seen[0].commit[:8]} has {_describe(seen[1])}")
    return not problems and first is not None, problems, first


def label_size(versions: list[Version], records: dict) -> tuple[int | None, list[Version]]:
    """(the size every record that lists the label states, those records). A record lists the label
    when it has a cluster or a single size for it; it states the sizes of its clusters that have one.
    None when the records state two sizes or none."""
    sizes, relied = set(), []
    for v in versions:
        if not v.records_node_sizes:
            continue
        r = records[v.commit]
        stated = {c.gpus_per_node for c in r.clusters if c.gpus_per_node is not None}
        if r.gpus_per_node is not None:
            stated.add(r.gpus_per_node)
        if stated:
            sizes |= stated
            relied.append(v)
    return (next(iter(sizes)) if len(sizes) == 1 else None), relied


def _describe(key) -> str:
    return f"{key[0]} GPUs per node on {','.join(key[1])}"


def _exact(obj, keys: set, what: str) -> dict:
    if not isinstance(obj, dict) or set(obj) != keys:
        raise TableError(f"{what}: expected exactly the keys {sorted(keys)}, got "
                         f"{sorted(obj) if isinstance(obj, dict) else type(obj).__name__}")
    return obj


def _day(v, what: str) -> str:
    try:
        if isinstance(v, str) and date.fromisoformat(v).isoformat() == v:
            return v
    except ValueError:
        pass
    raise TableError(f"{what}: {v!r} is not a YYYY-MM-DD date")


def _size(v, what: str, allow_none: bool) -> int | None:
    if v is None and allow_none:
        return None
    if isinstance(v, int) and not isinstance(v, bool) and v > 0:
        return v
    raise TableError(f"{what}: {v!r} is not a positive integer")


def parse(doc) -> Table:
    """The table from its JSON document, refusing any key, type or value it does not define."""
    _exact(doc, {"inferencex", "versions", "labels"}, "table")
    _exact(doc["inferencex"], {"repository"}, "inferencex")
    if not isinstance(doc["versions"], list) or not doc["versions"]:
        raise TableError("versions: expected a non-empty list")
    versions = []
    for i, d in enumerate(doc["versions"]):
        _exact(d, {"commit", "date", "path", "records_node_sizes"}, f"versions[{i}]")
        if not isinstance(d["commit"], str) or not _HASH.match(d["commit"]):
            raise TableError(f"versions[{i}].commit: {d['commit']!r} is not a full commit hash")
        if not isinstance(d["path"], str) or not d["path"]:
            raise TableError(f"versions[{i}].path: {d['path']!r} is not a path")
        if not isinstance(d["records_node_sizes"], bool):
            raise TableError(f"versions[{i}].records_node_sizes: {d['records_node_sizes']!r} is not a boolean")
        versions.append(Version(d["commit"], _day(d["date"], f"versions[{i}].date"), d["path"], d["records_node_sizes"]))
    if len({v.commit for v in versions}) != len(versions):
        raise TableError("versions: a commit is listed twice")
    if [v.date for v in versions] != sorted(v.date for v in versions):
        raise TableError("versions: not in date order")
    recording = [v for v in versions if v.records_node_sizes]
    labels = {}
    if not isinstance(doc["labels"], dict):
        raise TableError("labels: expected an object")
    for name, d in doc["labels"].items():
        what = f"labels.{name}"
        _exact(d, {"stable", "problems", "first_recorded", "records"}, what)
        if not isinstance(d["records"], dict) or set(d["records"]) != {v.commit for v in recording}:
            raise TableError(f"{what}.records: expected one record for each version that records node sizes")
        records = {}
        for commit, r in d["records"].items():
            rw = f"{what}.records.{commit[:8]}"
            _exact(r, {"gpus_per_node", "problem", "clusters"}, rw)
            clusters = []
            for j, c in enumerate(r["clusters"]):
                _exact(c, {"id", "gpus_per_node", "source"}, f"{rw}.clusters[{j}]")
                if not isinstance(c["id"], str) or not c["id"]:
                    raise TableError(f"{rw}.clusters[{j}].id: {c['id']!r} is not a cluster id")
                if c["source"] is not None and not (isinstance(c["source"], str) and _SOURCE.match(c["source"])):
                    raise TableError(f"{rw}.clusters[{j}].source: {c['source']!r} is not file:line")
                if (c["gpus_per_node"] is None) != (c["source"] is None):
                    raise TableError(f"{rw}.clusters[{j}]: gpus_per_node and source are both set or both null")
                clusters.append(Cluster(c["id"], _size(c["gpus_per_node"], f"{rw}.clusters[{j}].gpus_per_node", True), c["source"]))
            size = _size(r["gpus_per_node"], f"{rw}.gpus_per_node", True)
            if (size is None) != (isinstance(r["problem"], str) and bool(r["problem"])):
                raise TableError(f"{rw}: a record has a problem exactly when it has no size")
            records[commit] = Record(size, r["problem"], tuple(clusters))
        stable, problems, first = stability(versions, records)
        if d["stable"] is not stable or d["problems"] != problems:
            raise TableError(f"{what}: stable/problems do not match the records (they give stable={stable}, problems={problems})")
        want_first = None if first is None else {"commit": first.commit, "date": first.date}
        if d["first_recorded"] != want_first:
            raise TableError(f"{what}.first_recorded: {d['first_recorded']!r} does not match the records ({want_first!r})")
        size, relied = label_size(versions, records)
        labels[name] = Label(stable, tuple(problems), first, records, size, tuple(relied))
    return Table(tuple(versions), labels)


def load(path: Path = DATA) -> Table:
    return parse(json.loads(Path(path).read_text()))


@dataclass(frozen=True)
class NodeSize:
    """The decision for one row. gpus_per_node is None when the scenario states no node size:
    the catalog entry fixes it, or reason says why none is known."""
    gpus_per_node: int | None = None
    provenance: str | None = None         # `cluster.gpus_per_node: <source>`
    substitution: dict | None = None      # the G2 later_record substitution, if one was taken
    reason: dict | None = None            # a G5 {"code", "subject"}


def _short(commit: str) -> str:
    return commit[:8]


def resolve(table: Table, label: str, *, run_date: str, launch_size: int | None, fixes_packaging: bool) -> NodeSize:
    """The node size for a row of hardware `label` measured on `run_date` (YYYY-MM-DD, or a
    timestamp starting with it).

    Order of sources: (i) the run's launch configuration; (ii) this table; (iii) none, which is
    G5 value_not_recorded. A chip whose catalog entry fixes packaging states no node size, so it
    uses neither. A launch size that differs from the record in force at the run's date is G5
    value_conflict. A row before the label's first record is not compared: the table has no
    record for that time."""
    if fixes_packaging:
        return NodeSize()
    day = _day(str(run_date)[:10], "run_date")
    lab = table.labels.get(label)
    in_force = None
    if lab is not None and lab.first_recorded is not None and day >= lab.first_recorded.date:
        v = max((v for v in table.versions if v.records_node_sizes and v.date <= day),
                key=lambda v: (v.date, table.versions.index(v)))
        in_force = (v, lab.records[v.commit])
    table_size = in_force[1].gpus_per_node if in_force else None
    if launch_size is not None:
        if table_size is not None and table_size != launch_size:
            return NodeSize(reason={"code": "value_conflict", "subject": SUBJECT})
        return NodeSize(launch_size, f"{SUBJECT}: launch_config")
    if table_size is not None:
        return NodeSize(table_size, f"{SUBJECT}: InferenceX runners.yaml at {_short(in_force[0].commit)}")
    if lab is not None and lab.stable and day < lab.first_recorded.date:
        f = lab.first_recorded
        sub = {"kind": "later_record", "subject": SUBJECT, "record": f"{f.path} at {f.commit}", "date": f.date,
               "detail": f"taken from InferenceX runners.yaml at {_short(f.commit)}, recorded after the run "
                         f"({_short(f.commit)} of {f.date})"}
        return NodeSize(lab.records[f.commit].gpus_per_node,
                        f"{SUBJECT}: InferenceX runners.yaml at {_short(f.commit)}", sub)
    if lab is not None and lab.label_size is not None and lab.relied_on:
        last = lab.relied_on[-1]
        record = f"label {label} in " + "; ".join(f"{v.path} at {v.commit}" for v in lab.relied_on)
        sub = {"kind": "later_record", "subject": SUBJECT, "record": record, "date": last.date,
               "detail": f"taken from the records of label {label} in InferenceX runners.yaml "
                         f"({', '.join(f'{_short(v.commit)} of {v.date}' for v in lab.relied_on)}), which all state "
                         f"{lab.label_size}; no record lists the runner"}
        return NodeSize(lab.label_size, f"{SUBJECT}: InferenceX runners.yaml, label {label}", sub)
    return NodeSize(reason={"code": "value_not_recorded", "subject": SUBJECT})
